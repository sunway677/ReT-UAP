def dataset_fingerprint(dataset):
    h = hashlib.sha1()
    for ann in dataset.ann:
        h.update(json.dumps([ann['image'], ann['caption']]).encode('utf-8'))
    return h.hexdigest()


def _load_cache(path, meta):
    if os.path.exists(path):
        data = torch.load(path, map_location='cpu', weights_only=False)
        if data.get('meta') == meta:
            print(f'[cache] loaded {path}')
            return data
        print(f'[cache] {path} was built with different settings; recomputing')
    return None


def _save_cache(path, meta, payload):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = f'{path}.tmp{os.getpid()}'
    torch.save(dict(payload, meta=meta), tmp)
    os.replace(tmp, path)


@torch.no_grad()
def compute_banks(surrogates, primary, dataset, args, cache_dir, fingerprint, image_res):
    """Clean feature banks (Eq. 1) of all surrogates and the primary's
    all-caption generator conditions (Eq. 10), in dataset order."""
    banks, todo = {}, []
    for s in surrogates:
        meta = {'version': CACHE_VERSION, 'kind': 'bank', 'model': s.name, 'data': fingerprint,
                'image_res': image_res}
        data = _load_cache(os.path.join(cache_dir, f'bank_{s.tag}.pth'), meta)
        if data is None:
            todo.append((s, meta))
        else:
            banks[s.name] = (data['V'], data['U'])
    cond_meta = {'version': CACHE_VERSION, 'kind': 'cond_txt', 'model': primary.name, 'data': fingerprint}
    cond_path = os.path.join(cache_dir, f'cond_txt_{primary.tag}.pth')
    data = _load_cache(cond_path, cond_meta)
    cond = None if data is None else data['e_txt']
    if not todo and cond is not None:
        return banks, cond

    loader = DataLoader(dataset, batch_size=args.batch_size, shuffle=False, drop_last=False,
                        num_workers=args.num_workers, collate_fn=dataset.collate_fn)
    feats = {s.name: ([], []) for s, _ in todo}
    conds = []
    print(f'[bank] extracting features of {[s.name for s, _ in todo]}'
          f'{" and the primary conditions" if cond is None else ""} on {len(dataset)} images')
    for step, (images, texts_group, _, _) in enumerate(loader):
        first = [group[0] for group in texts_group]
        for s, _ in todo:
            images_dev = images.to(s.device, non_blocking=True)
            feats[s.name][0].append(s.image_features(images_dev).cpu())
            feats[s.name][1].append(s.text_features(first).cpu())
        if cond is None:
            all_caps = [t for group in texts_group for t in group]
            raw = primary.raw_text_features(all_caps).cpu()
            k = 0
            for group in texts_group:
                conds.append(raw[k:k + len(group)].mean(dim=0))   # mean of raw f_txt (Eq. 10)
                k += len(group)
        if (step + 1) % 50 == 0:
            print(f'[bank] {step + 1}/{len(loader)} batches')
    for s, meta in todo:
        V, U = torch.cat(feats[s.name][0]), torch.cat(feats[s.name][1])
        banks[s.name] = (V, U)
        _save_cache(os.path.join(cache_dir, f'bank_{s.tag}.pth'), meta, {'V': V, 'U': U})
    if cond is None:
        cond = torch.nn.functional.normalize(torch.stack(conds), dim=-1)
        _save_cache(cond_path, cond_meta, {'e_txt': cond})
    return banks, cond


def build_targets(s, bank, n_clusters, args, device, cache_dir, fingerprint):
    """Offline target construction of one surrogate (Eqs. 2-9, 18, 20)."""
    V, U = bank
    params = dict(n_clusters=n_clusters, hub_k=args.hub_k, score_weights=tuple(args.score_weights),
                  ot_reg=args.ot_reg, ot_iters=args.ot_iters,
                  margin_range=(args.margin_min, args.margin_max), seed=args.seed)
    meta = {'version': CACHE_VERSION, 'kind': 'targets', 'model': s.name, 'data': fingerprint,
            'params': {k: list(v) if isinstance(v, tuple) else v for k, v in params.items()}}
    path = os.path.join(cache_dir, f'targets_{s.tag}.pth')
    st = SurrogateTargets(V, U, device=device, **params)
    data = _load_cache(path, meta)
    if data is not None:
        try:
            st.load_state_dict(data['state'])
        except ValueError as err:   # stale cache (different banks or settings)
            print(f'[cache] {path}: {err}; recomputing')
            data = None
    if data is None:
        print(f'[targets] building {s.name}: N={V.shape[0]}, C={n_clusters}')
        st.build()
        _save_cache(path, meta, {'state': st.state_dict()})
    return st


def compute_positions(s, captions, num_positions, cache_dir, fingerprint, chunk=256):
    """K_p critical token positions of every first caption for surrogate s
    (Sec. 4.3.2). Returns (positions, extras) LongTensors (N, K_p), -1 = none."""
    meta = {'version': CACHE_VERSION, 'kind': 'positions', 'model': s.name, 'data': fingerprint,
            'K_p': num_positions}
    path = os.path.join(cache_dir, f'positions_{s.tag}_k{num_positions}.pth')
    data = _load_cache(path, meta)
    if data is not None:
        return data['positions'], data['extras']
    pos = torch.full((len(captions), num_positions), -1, dtype=torch.long)
    ext = torch.full((len(captions), num_positions), -1, dtype=torch.long)
    print(f'[positions] {s.name}: ranking the words of {len(captions)} captions')
    for start in range(0, len(captions), chunk):
        p, e = s.critical_positions(captions[start:start + chunk], num_positions)
        for i, (row_p, row_e) in enumerate(zip(p, e)):
            pos[start + i, :len(row_p)] = torch.as_tensor(row_p, dtype=torch.long)
            ext[start + i, :len(row_e)] = torch.as_tensor(row_e, dtype=torch.long)
        if (start // chunk + 1) % 20 == 0:
            print(f'[positions] {s.name}: {start + chunk}/{len(captions)}')
    short = int((pos < 0).any(dim=1).sum())
    if short:
        print(f'[positions] {s.name}: {short} captions have fewer than {num_positions} selectable words')
    _save_cache(path, meta, {'positions': pos, 'extras': ext})
    return pos, ext


def lookup_positions(pos, ext, idx):
    rows_p, rows_e = pos[idx].tolist(), ext[idx].tolist()
    positions = [[p for p in rp if p >= 0] for rp in rows_p]
    extras = [[e for p, e in zip(rp, re) if p >= 0] for rp, re in zip(rows_p, rows_e)]
    return positions, extras



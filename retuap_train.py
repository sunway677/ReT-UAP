def save_epoch(save_dir, epoch, delta_x, delta_t, img_gen, txt_gen, selector, args, primary):
    os.makedirs(save_dir, exist_ok=True)
    torch.save(delta_x.detach().float().cpu(), os.path.join(save_dir, f'uap_noise-{epoch}.pth'))
    torch.save(delta_t.detach().float().cpu(), os.path.join(save_dir, f'uap_embedding-{epoch}.pth'))
    torch.save({'G_x': img_gen.G_x.state_dict(), 'f_score': img_gen.f_score.state_dict(),
                'G_t': txt_gen.G_t.state_dict(),
                'z_x': img_gen.G_x.z.detach().cpu(), 'z_t': txt_gen.G_t.z.detach().cpu(),
                'token_norm_range': (float(txt_gen.min_norm), float(txt_gen.max_norm)),
                'ucb': selector.state_dict(), 'primary': primary.name, 'epoch': epoch,
                'args': vars(args)},
               os.path.join(save_dir, f'generators-{epoch}.pth'))
    # Keep only the latest epoch's artifacts.
    for fname in os.listdir(save_dir):
        for prefix in ('uap_noise-', 'uap_embedding-', 'generators-'):
            if fname.startswith(prefix) and fname.endswith('.pth') and fname != f'{prefix}{epoch}.pth':
                os.remove(os.path.join(save_dir, fname))


def run_training(args, config, primary, auxiliaries, dataset, device, save_dir, cache_dir,
                 token_norm_range):
    """Algorithm 1. primary / auxiliaries are Surrogate objects; dataset is the
    (test-filtered) training set; token_norm_range = (min, max, d_tok)."""
    surrogates = [primary] + list(auxiliaries)
    same_system = {s.name: s.family == primary.family for s in surrogates}
    N = len(dataset)
    fingerprint = dataset_fingerprint(dataset)
    print(f'[train] primary={primary.name}  same-system={[s.name for s in auxiliaries if same_system[s.name]]}'
          f'  cross-system={[s.name for s in auxiliaries if not same_system[s.name]]}  N={N}')

    # ---------------- offline stage ----------------
    banks, e_txt_all = compute_banks(surrogates, primary, dataset, args, cache_dir, fingerprint,
                                     config['image_res'])
    n_clusters = num_clusters(N, args.cluster_ratio)
    targets = {s.name: build_targets(s, banks[s.name], n_clusters, args, device, cache_dir, fingerprint)
               for s in surrogates}
    first_captions = [dataset.text[dataset.img2txt[i][0]] for i in range(N)]
    positions = {s.name: compute_positions(s, first_captions, args.num_text_positions, cache_dir, fingerprint)
                 for s in surrogates if same_system[s.name]}
    banks = {name: (V.to(device), U.to(device)) for name, (V, U) in banks.items()}
    e_txt_all = e_txt_all.to(device)

    # ---------------- generators ----------------
    min_norm, max_norm, d_tok = token_norm_range
    for s in surrogates:
        if same_system[s.name] and s.token_dim != d_tok:
            raise ValueError(f'{s.name} token embeddings have dim {s.token_dim}, delta_t has {d_tok}')
    d_feat = banks[primary.name][0].shape[1]
    eps = args.eps / 255.0
    torch.manual_seed(args.seed)   # generator initialization independent of the offline caches
    img_gen = ImagePerturbationGenerator(d_feat, eps, image_size=config['image_res']).to(device)
    txt_gen = TextPerturbationGenerator(d_feat, args.num_text_positions, d_tok, min_norm, max_norm).to(device)
    params = list(img_gen.parameters()) + list(txt_gen.parameters())
    optimizer = torch.optim.Adam(params, lr=args.lr, betas=(0.5, 0.999))
    selector = UCBSurrogateSelector([s.name for s in auxiliaries], c_ucb=args.ucb_exploration,
                                    eta=args.reward_momentum, lambda_sur=args.lambda_sur,
                                    min_select_ratio=args.min_select_ratio,
                                    norm_ema_rate=args.norm_ema_rate, eps0=EPS0)

    g = torch.Generator()
    g.manual_seed(args.seed)
    loader = DataLoader(dataset, batch_size=args.batch_size, shuffle=True, drop_last=True,
                        num_workers=args.num_workers, collate_fn=dataset.collate_fn, generator=g)
    n_batches = len(loader)
    if n_batches == 0:
        raise ValueError('the training set is smaller than one batch')
    print(f'[train] {args.epochs} epochs x {n_batches} batches, E_warm={args.aux_warmup_epochs}, '
          f'eps={args.eps}/255, K_p={args.num_text_positions}, d_feat={d_feat}, d_tok={d_tok}, '
          f'norm range=[{min_norm:.4f}, {max_norm:.4f}]')

    for epoch in range(args.epochs):
        img_gen.train()
        txt_gen.train()
        aux_on = epoch >= args.aux_warmup_epochs and len(auxiliaries) > 0
        if aux_on:
            selector.start_epoch(n_batches)
        log = {'img': 0.0, 'txt': 0.0, 'sur': 0.0, 'n': 0}
        last = None
        for step, (images, texts_group, img_ids, _) in enumerate(loader):
            idx_cpu = torch.as_tensor(img_ids, dtype=torch.long)
            idx_dev = idx_cpu.to(device)
            images = images.to(device, non_blocking=True)
            captions = [group[0] for group in texts_group]

            # Perturbations (Eqs. 10, 13, 14).
            e_txt = e_txt_all[idx_dev]
            e_img = torch.nn.functional.normalize(banks[primary.name][0][idx_dev].mean(dim=0, keepdim=True), dim=-1)
            delta_x, _, _ = img_gen(e_txt)
            delta_t = txt_gen(e_img)

            # Primary surrogate: L_img^(1) + L_txt^(1).
            l_img, l_txt = surrogate_losses(primary, True, images, captions, delta_x, delta_t, idx_cpu,
                                            banks, targets, positions, args)
            loss = l_img + l_txt

            # Auxiliary surrogate after warm-up (Algorithm 1 order: select, loss,
            # normalized reward, reward update, gated loss).
            if aux_on:
                k = selector.select()
                s = auxiliaries[k]
                a_img, a_txt = surrogate_losses(s, same_system[s.name], images, captions, delta_x, delta_t,
                                                idx_cpu, banks, targets, positions, args)
                l_s = a_img if a_txt is None else a_img + a_txt
                selector.update(k, l_s.item())
                l_sur = selector.gate(k) * l_s
                loss = loss + l_sur
                log['sur'] += l_sur.item()

            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            optimizer.step()

            last = (delta_x.detach(), delta_t.detach())
            log['img'] += l_img.item()
            log['txt'] += l_txt.item()
            log['n'] += 1
            if (step + 1) % 20 == 0 or step + 1 == n_batches:
                n = log['n']
                counts = ' '.join(f'{name}:{int(c)}' for name, c in zip(selector.names, selector.epoch_counts)) \
                    if aux_on else 'warm-up'
                print(f'E{epoch} B{step + 1}/{n_batches} | L_img^1 {log["img"] / n:.4f} '
                      f'L_txt^1 {log["txt"] / n:.4f} L_sur {log["sur"] / n:.4f} | {counts}', flush=True)
                log = {'img': 0.0, 'txt': 0.0, 'sur': 0.0, 'n': 0}

        save_epoch(save_dir, epoch, last[0], last[1], img_gen, txt_gen, selector, args, primary)
        print(f'[train] epoch {epoch} saved to {save_dir}')
        if aux_on:
            print(selector.summary())
    return img_gen, txt_gen, selector, optimizer


def main(argv=None):
    args = parse_args(argv)
    config = load_yaml(args.config)
    test_config = load_yaml(args.test_config)
    if config['dataset'] != test_config['dataset']:
        raise ValueError(f"--config is {config['dataset']} but --test_config is {test_config['dataset']}; "
                         f"pass the matching test config")
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    set_seed(args.seed)
    cudnn.benchmark = True

    dataset_name = config['dataset']
    primary_tag = model_tag(args.primary_encoder)
    token_norm_range = load_token_norm_range(args.primary_encoder, dataset_name)
    dataset = build_train_dataset(config, test_config)

    names = [args.primary_encoder] + [n for n in SURROGATE_POOL if n != args.primary_encoder]
    surrogates = [load_surrogate(n, args, config, device) for n in names]
    save_dir = os.path.join(args.save_dir, primary_tag, dataset_name)
    cache_dir = os.path.join(args.save_dir, 'cache', dataset_name)
    run_training(args, config, surrogates[0], surrogates[1:], dataset, device, save_dir, cache_dir,
                 token_norm_range)
    print('Training complete.')


if __name__ == '__main__':
    main()

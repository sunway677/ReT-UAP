"""
ReT-UAP training (Algorithm 1 of the manuscript "ReT-UAP: Rethinking
Multi-Surrogate Universal Adversarial Perturbations on Vision-Language
Pre-trained Models", under review at Information Fusion).

Surrogate pool: ALBEF, TCL, BLIP, XVLM, CLIP ViT-B/16 and ViT-B/32. The model
given by --primary_encoder is the primary surrogate, the other five are the
auxiliaries; auxiliaries of the primary's family (BERT-tokenizer models or CLIP)
are same-system, the others cross-system (Sec. 4.5.1).

Offline stage (once per surrogate; cached in <save_dir>/cache/<dataset>/)
  1. Clean feature bank v_i = norm(f_img(x_i)), u_i = norm(f_txt(t_{i,1})) on the
     training set, first caption only (Eq. 1).
  2. Cross-modal prototypes, hubness / diversity / mismatch scores, entropic OT,
     soft targets, adaptive margins and informed negatives of every surrogate:
     retuap_targets.SurrogateTargets (Eqs. 2-9, 18, 20).
  3. The K_p critical token positions of every first caption, for each surrogate
     of the primary's family, computed with that surrogate (Sec. 4.3.2).
  4. Image-generator conditions e_txt_i = norm(mean_k f_txt(t_{i,k})) of the
     primary surrogate over all K captions of image i (Eq. 10).

Online stage, for every mini-batch B (Algorithm 1)
  delta_hat_i = clip(G_x(z_x; e_txt_i)), a = softmax(f_score(delta_hat)),
  delta_x = clip(sum_i a_i delta_hat_i)                               (Eq. 14)
  delta_t = G_t(z_t; e_img), e_img = norm(mean_{i in B} v_i^(1))       (Eq. 13)
  v_adv_i = norm(f_img(x_i + delta_x)), u_adv_i = norm(f_txt(t_{i,1} (+) delta_t))  (Eq. 15)
  L_img, L_txt: margin contrastive losses with soft targets, adaptive margins,
  in-batch clean features and informed negatives (Eqs. 16-22)
  epoch <  E_warm: L = L_img^(1) + L_txt^(1)
  epoch >= E_warm: s* = argmax_s UCB(s) (Eq. 26, with the selection floor),
                   L^(s*) = L_img^(s*) [+ L_txt^(s*) if same-system]  (Eq. 23),
                   L_hat(s*) (Eq. 24), R_bar(s*) update (Eq. 25),
                   L_sur = lambda_sur * sigmoid(R_bar(s*)) * L^(s*)    (Eq. 27; the
                   gate is a constant weight), L = L_img^(1) + L_txt^(1) + L_sur (Eq. 28)
  one backward pass of L and one Adam step on G_x, G_t and f_score.

Outputs in <save_dir>/<primary tag>/<dataset>/ (only the latest epoch is kept):
  uap_noise-<epoch>.pth      delta_x*, float32 (1, 3, H, W), H = W = image_res, in [-eps_x, eps_x]
  uap_embedding-<epoch>.pth  delta_t*, float32 (K_p, d_tok), rows norm-clamped
  generators-<epoch>.pth     G_x, f_score, G_t (incl. the fixed noises z_x, z_t) and the UCB state
delta_x* and delta_t* are the perturbations of the final training iteration
(Sec. 4.3.2, 'Inference').

Details the manuscript does not fix (chosen here, documented):
  * Training images listed in the --test_config annotation are removed from the
    training set (threat model: no access to test data).
  * Mini-batches are reshuffled every epoch (seeded) and the last incomplete
    batch is dropped.
  * K_neg (--k_neg) defaults to retuap_targets.DEFAULT_K_NEG = 21 = floor(64 / 3),
    the value used by the research code for batch size 64.
  * The running loss statistics of Eq. (24) are bias-corrected exponential
    moving averages with update rate --norm_ema_rate 0.01; eps0 = 1e-6.
  * Adam betas (0.5, 0.999) as in the research code.
  * Surrogate forward passes run under bfloat16 autocast on GPU.
  * CLIP surrogates receive the image and delta_x bilinearly resized to their
    input resolution.
  * delta_t is norm-clamped to the L2-norm range of the natural word embeddings
    of the primary's token-embedding table: the rows of
    word_embedding_<TAG>_<DATASET>.pth (generated by
    scripts/generate_word_embeddings.py) listed in the family's whole-word
    vocabulary filter word_idx_BERT.npy / word_idx_CLIP.npy (working directory).

Usage (from the repository root):
  python retuap_train.py --primary_encoder ALBEF \
      --config ./configs/Retrieval_flickr_train.yaml \
      --test_config ./configs/Retrieval_flickr_test.yaml \
      --checkpoint_dir ./checkpoint --save_dir output_retuap
"""


def build_train_dataset(config, test_config):
    """Training set with every image of the test annotation removed (U6)."""
    transform = transforms.Compose([
        transforms.Resize((config['image_res'], config['image_res']),
                          interpolation=transforms.InterpolationMode.BICUBIC),
        transforms.ToTensor(),
    ])
    exclude = load_image_keys(test_config['annotation_file'])
    dataset = paired_dataset(config['annotation_file'], transform, config['image_root'],
                             exclude_images=exclude)
    print(f"[data] {config['annotation_file']}: removed {dataset.num_excluded} training images that "
          f"appear in {test_config['annotation_file']}; {len(dataset)} images remain")
    return dataset


def load_surrogate(name, args, config, device):
    from utils import load_model
    is_clip = name in CLIP_FAMILY
    ckpt = '' if is_clip else os.path.join(args.checkpoint_dir, name, f"{config['dataset']}.pth")
    print(f'[model] loading {name} {ckpt}')
    model, ref_model, tokenizer = load_model(name, ckpt, 'bert-base-uncased', config, device)
    del ref_model
    model = model.to(device).float()
    return Surrogate(name, model, None if is_clip else tokenizer)


def load_token_norm_range(primary_name, dataset_name, path=None, vocab_path=None):
    """L2-norm range of the natural word embeddings of the primary's token-embedding
    table (C2 word file), i.e. of its rows listed in the family's whole-word
    vocabulary filter; special tokens and sub-word fragments are excluded."""
    path = path or f'word_embedding_{model_tag(primary_name)}_{dataset_name}.pth'
    vocab_path = vocab_path or ('word_idx_CLIP.npy' if primary_name in CLIP_FAMILY else 'word_idx_BERT.npy')
    for p in (path, vocab_path):
        if not os.path.exists(p):
            raise FileNotFoundError(f'{p} not found; run scripts/generate_word_embeddings.py first')
    table = torch.load(path, map_location='cpu', weights_only=False).float()
    ids = torch.from_numpy(np.load(vocab_path).astype(np.int64))
    norms = table[ids].norm(dim=1)
    return float(norms.min()), float(norms.max()), int(table.shape[1])



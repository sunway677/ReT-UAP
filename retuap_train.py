def branch_loss(branch, adv, idx_cpu, bank, targets, args):
    """L_img (branch 'img', Eqs. 16-21) or L_txt (branch 'txt', Eq. 22) of one surrogate."""
    V, U = bank
    feats = V if branch == 'img' else U
    dev = adv.device
    tar_a, tar_b = targets.targets(idx_cpu, branch)
    margin = targets.margins(idx_cpu, branch)
    negatives = None
    if args.k_neg > 0:
        neg_idx = targets.informed_negatives(idx_cpu, branch, args.k_neg)
        if neg_idx is not None and len(neg_idx) > 0:
            negatives = feats[torch.as_tensor(neg_idx, dtype=torch.long).to(feats.device)].to(dev)
    clean = feats[idx_cpu.to(feats.device)].to(dev)
    return margin_contrastive_loss(adv, (tar_a.to(dev, torch.float32), tar_b.to(dev, torch.float32)),
                                   margin.to(dev, torch.float32), clean, negatives, args.temperature)


def surrogate_losses(s, same_system, images, captions, delta_x, delta_t, idx_cpu,
                     banks, targets, positions, args):
    """(L_img^(s), L_txt^(s) or None) for surrogate s (Eq. 23)."""
    v_adv = s.image_features(images.to(s.device), delta_x.to(s.device))
    l_img = branch_loss('img', v_adv, idx_cpu, banks[s.name], targets[s.name], args)
    if not same_system:
        return l_img, None
    pos, ext = lookup_positions(*positions[s.name], idx_cpu)
    u_adv = s.adv_text_features(captions, delta_t.to(s.device), pos, ext)
    l_txt = branch_loss('txt', u_adv, idx_cpu, banks[s.name], targets[s.name], args)
    return l_img, l_txt


